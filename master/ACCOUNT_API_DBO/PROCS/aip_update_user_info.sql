CREATE OR REPLACE PROCEDURE account_api_dbo.aip_update_user_info(
  P_EMAIL_I IN VARCHAR,
  P_FIRST_NAME_I IN VARCHAR,
  P_LAST_NAME_I IN VARCHAR,
  P_USER_NAME_I IN VARCHAR,
  P_BIO_I IN VARCHAR,
  P_NOTIFICATIONS_I IN BOOLEAN,
  P_PHONE_NBR_I IN VARCHAR,
  P_ADMIN_FLAG_I IN VARCHAR
)
AS $$
BEGIN
  UPDATE ACCOUNT_DBO.USERS
    SET FIRST_NAME = COALESCE(P_FIRST_NAME_I, FIRST_NAME),
        LAST_NAME = COALESCE(P_LAST_NAME_I, LAST_NAME),
        USER_NAME = COALESCE(P_USER_NAME_I, USER_NAME),
        BIO = COALESCE(P_BIO_I, BIO),
        NOTIFICATIONS = COALESCE(P_NOTIFICATIONS_I, NOTIFICATIONS),
        PHONE_NBR = COALESCE(P_PHONE_NBR_I, PHONE_NBR),
        ADMIN_FLAG = COALESCE(P_ADMIN_FLAG_I, ADMIN_FLAG),
        UPDATE_ID = CURRENT_USER,
        UPDATE_TS = CURRENT_TIMESTAMP
    WHERE UPPER(EMAIL) = UPPER(P_EMAIL_I);
  
  EXCEPTION
    WHEN OTHERS THEN
      RAISE EXCEPTION 'Error in procedure account_api_dbo.aip_update_user_info';
END;
$$ language plpgsql;